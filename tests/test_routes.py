"""
Route manifest: for every API route, who may call it, whether it stays on this dashboard or
goes to the selected remote server, and what the activity log calls it. The rules live in
backend/access.py, backend/remotes.py (LOCAL_ONLY) and backend/audit.py - this test keeps
them honest:

- a changing route (POST/PUT/PATCH/DELETE) without its own permission rule fails
  (otherwise it silently falls back to "admins only" - or a forgotten public path);
- any change to permissions, forwarding or labels shows up as a diff of tests/routes.txt.

After an intended change:  UPDATE_ROUTES=1 venv/bin/python -m pytest tests/test_routes.py
"""

import itertools
import os
import re

import access
import audit
import remotes
from helpers import iter_routes

MANIFEST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "routes.txt")
WRITE = {"POST", "PUT", "PATCH", "DELETE"}
# Values tried for path parameters until one matches a rule (ids are hex of different lengths)
SAMPLES = ["a1b2c3d4e5f6a7b8", "a1b2c3d4e5f6", "a1b2c3d4e5", "a1b2c3d4", "a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6",
           "1234", "abc", "AA:BB:CC:DD:EE:FF", "approve", "docker", "run", "check", "start", "delete", "x"]
# Changing routes that need no permission rule: they check something else themselves
SELF_CHECKED = {
    "/api/agent/wol": "agent only: token of the main dashboard",
    "/api/webhook/github": "HMAC signature",
    "/api/x/{token}/upload": "exchange link token",
}


def _variants(path):
    params = re.findall(r"\{[^}]+\}", path)
    for combo in itertools.product(SAMPLES, repeat=len(params)):
        s = path
        for v in combo:
            s = re.sub(r"\{[^}]+\}", v, s, count=1)
        yield s


def _rule_match(method, path):
    """A concrete path for this route that an explicit access rule covers, or None. Rules are
    checked in order (specific ones first, catch-alls later), so the path that hits the
    earliest rule describes the route best."""
    best, best_i = None, len(access._COMPILED)
    for v in _variants(path):
        for i, (m, rx, _) in enumerate(access._COMPILED[:best_i]):
            if (m == "*" or m == method) and rx.match(v):
                best, best_i = v, i
                break
    return best


def _public(app_module, path):
    return path in app_module.PUBLIC_PATHS or path.startswith(("/api/x/", "/api/public/"))


def _manifest(app_module):
    lines, unclassified = [], []
    for r in iter_routes(app_module.app.routes):
        path = getattr(r, "path", "")
        if not path.startswith("/api/"):
            continue
        for method in sorted((getattr(r, "methods", None) or set()) - {"HEAD", "OPTIONS"}):
            sample = _rule_match(method, path)
            concrete = sample or next(_variants(path))
            if _public(app_module, path):
                perm = "public"
            elif sample:
                perm = access.required_permission(method, sample) or "public-view"
            elif path in SELF_CHECKED:
                perm = "self-checked"
            else:
                perm = (access.required_permission(method, concrete) or "public-view") + " (default)"
                if method in WRITE:
                    unclassified.append(f"{method} {path}")
            where = "local" if remotes.LOCAL_ONLY.match(concrete) else "remote"
            line = f"{method:6} {path}  perm={perm}  {where}"
            if method in WRITE:
                kind = audit.classify(method, concrete)
                line += f"  audit={kind[1] if kind else '-'}"
            lines.append(line)
    return sorted(set(lines)), unclassified


def test_every_changing_route_has_a_permission_rule(app_module):
    _, unclassified = _manifest(app_module)
    assert not unclassified, ("Changing routes without a rule in backend/access.py (they would be admin-only by "
                              "accident) - add a rule, or list them in SELF_CHECKED:\n" + "\n".join(unclassified))


def test_manifest_is_current(app_module):
    lines, _ = _manifest(app_module)
    text = "# Generated by tests/test_routes.py - do not edit (UPDATE_ROUTES=1 to refresh)\n" + "\n".join(lines) + "\n"
    if os.environ.get("UPDATE_ROUTES"):
        with open(MANIFEST, "w") as f:
            f.write(text)
    with open(MANIFEST) as f:
        old = f.read()
    if old != text:
        import difflib
        diff = "\n".join(difflib.unified_diff(old.splitlines(), text.splitlines(), "routes.txt", "now", lineterm="", n=0))
        raise AssertionError("Permissions, forwarding or activity-log labels of routes changed. If intended, run "
                             "UPDATE_ROUTES=1 venv/bin/python -m pytest tests/test_routes.py and commit tests/routes.txt.\n" + diff)
